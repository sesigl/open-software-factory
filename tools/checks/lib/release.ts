// The release files of each published package: its publish workflow, its release-please entry and its version in the
// release-please manifest. `osf release-files` writes them and RELEASE compares them, so both use this one source.
import { readFileSync } from "node:fs";
import type { Repo } from "./repo.ts";
import { shortName, type Unit, workspace } from "./workspace.ts";

export const CONFIG = "release-please-config.json";
export const MANIFEST = ".release-please-manifest.json";
export const TEMPLATE = "tools/scaffold/publish-workflow.yml";
/** The first line of every publish workflow that `osf release-files` writes. */
export const GENERATED = "# Generated by `osf release-files`";

export type Entry = Record<string, unknown>;

/** The packages that are published: every workspace package that is not private. */
export const published = (repo: Repo): Unit[] => workspace(repo).filter((unit) => unit.published);

export const workflowOf = (unit: Unit): string => `.github/workflows/publish-${shortName(unit.name)}.yml`;

/** The publish workflow of `unit`, rendered from the template. */
export function renderWorkflow(unit: Unit): string {
  return readFileSync(new URL(`../../scaffold/${TEMPLATE.split("/").at(-1)}`, import.meta.url), "utf8")
    .replaceAll("{{name}}", unit.name)
    .replaceAll("{{dir}}", unit.dir)
    .replaceAll("{{component}}", shortName(unit.name));
}

/** The keys of a release-please entry that must name `unit`; other keys, such as `extra-files`, may differ. */
export const entryOf = (unit: Unit): Entry => ({
  "release-type": "node",
  "package-name": unit.name,
  component: shortName(unit.name),
});

/** A new entry: the keys above, and the first version and the minor bumps before 1.0 of every new package. */
export const newEntryOf = (unit: Unit): Entry => ({
  ...entryOf(unit),
  "initial-version": "0.1.0",
  "bump-minor-pre-major": true,
});

/** The generated publish workflows in the repository. */
export const generatedWorkflows = (repo: Repo): string[] =>
  repo.match(".github/workflows/publish-*.yml").filter((file) => repo.read(file).startsWith(GENERATED));

export const readJson = <T>(repo: Repo, file: string, empty: T): T =>
  repo.exists(file) ? (JSON.parse(repo.read(file)) as T) : empty;
