import { scenario } from "@opensoftware/testkit";
import { DEMO_PACKAGE, DEMO_PREFIXES } from "./repo.ts";

scenario("SCN-REPO-035", async ({ sut, given, when, then }) => {
  await given('a module whose "src/cli.ts --help" lists the command "demo run" as "Run the demo."', async () => {
    await sut.files.put("$INPUT/docs/reference/scenario-prefixes.md", DEMO_PREFIXES);
    await sut.files.put("$INPUT/modules/demo/package.json", DEMO_PACKAGE);
    await sut.files.put(
      "$INPUT/modules/demo/src/cli.ts",
      'process.stdout.write("usage: demo <command>\\n\\nCommands:\\n  demo run    Run the demo.\\n\\nOptions:\\n  --help    Print this help.\\n");\n',
    );
  });

  await given(
    'its README has the marker "generated by make docs from src/cli.ts --help" under "## Commands"',
    async () => {
      await sut.files.put(
        "$INPUT/modules/demo/README.md",
        "# demo\n\n## Commands\n\n<!-- generated by make docs from src/cli.ts --help: do not edit -->\n\n## Notes\n\nNone.\n",
      );
    },
  );

  let run: Awaited<ReturnType<typeof sut.cli>>;
  await when('the developer runs "osf docs"', async () => {
    run = await sut.cli(["docs"]);
  });

  await then("the command exits with code 0", async () => {
    expect(run.exitCode, run.stdout + run.stderr).toBe(0);
  });

  await then('the module README has the row "| `demo run` | Run the demo. |"', async () => {
    const readme = await sut.files.read("$INPUT/modules/demo/README.md");
    expect(readme).toContain("| `demo run` | Run the demo. |");
  });
});
