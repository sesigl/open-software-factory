import { scenario } from "@opensoftware/testkit";
import { acceptedAdr } from "./repo.ts";

const INDEX = "$INPUT/docs/decisions/README.md";

/** The lines of the group below `heading`, up to the next heading. */
async function group(read: (path: string) => Promise<string>, heading: string): Promise<string[]> {
  const lines = (await read(INDEX)).split("\n");
  const start = lines.indexOf(heading);
  if (start < 0) return [];
  const rest = lines.slice(start + 1);
  const end = rest.findIndex((line) => line.startsWith("#"));
  return rest.slice(0, end < 0 ? undefined : end).filter((line) => line !== "");
}

scenario("SCN-REPO-201", async ({ sut, given, when, then }) => {
  const read = (path: string): Promise<string> => sut.files.read(path);

  await given(
    'an accepted ADR "0001" with the topic "tools", an accepted ADR "0002" with the topic "design-note" and the status note "amended by 0003"',
    async () => {
      await sut.files.put("$INPUT/docs/decisions/0001-demo.md", acceptedAdr("0001", "demo 0001"));
      await sut.files.put(
        "$INPUT/docs/decisions/0002-demo.md",
        acceptedAdr("0002", "demo 0002", "accepted; amended by 0003", "design-note"),
      );
    },
  );

  await given('an ADR "0003" with the topic "tools" and the status "superseded by 0001"', async () => {
    await sut.files.put("$INPUT/docs/decisions/0003-demo.md", acceptedAdr("0003", "demo 0003", "superseded by 0001"));
  });

  await given('"docs/decisions/README.md" has the marker "generated by make docs from ./"', async () => {
    await sut.files.put(
      INDEX,
      "# Decisions\n\n## Index\n\n<!-- generated by make docs from ./: do not edit -->\n\n## How to add one\n\nSee the skill.\n",
    );
  });

  let run: Awaited<ReturnType<typeof sut.cli>>;
  await when('the developer runs "osf docs"', async () => {
    run = await sut.cli(["docs"]);
  });

  await then("the command exits with code 0", async () => {
    expect(run.exitCode, run.stdout + run.stderr).toBe(0);
  });

  await then(
    '"docs/decisions/README.md" lists "- [0001](0001-demo.md) Adopt demo 0001" under "### The tools"',
    async () => {
      expect(await group(read, "### The tools")).toEqual(["- [0001](0001-demo.md) Adopt demo 0001"]);
    },
  );

  await then(
    '"docs/decisions/README.md" lists "- [0002](0002-demo.md) Adopt demo 0002 — amended by 0003" under "### Design notes: test and CI mechanics"',
    async () => {
      expect(await group(read, "### Design notes: test and CI mechanics")).toEqual([
        "- [0002](0002-demo.md) Adopt demo 0002 — amended by 0003",
      ]);
    },
  );

  await then(
    '"docs/decisions/README.md" lists "- [0003](0003-demo.md) Adopt demo 0003 — superseded by 0001" under "### Superseded, rejected and deprecated"',
    async () => {
      expect(await group(read, "### Superseded, rejected and deprecated")).toEqual([
        "- [0003](0003-demo.md) Adopt demo 0003 — superseded by 0001",
      ]);
      expect(await read(INDEX)).toContain("## How to add one\n\nSee the skill.\n");
    },
  );

  let check: Awaited<ReturnType<typeof sut.cli>>;
  await when('the developer runs "osf check DOCS-GEN"', async () => {
    check = await sut.cli(["check", "DOCS-GEN"]);
  });

  await then("the command exits with code 0", async () => {
    expect(check.exitCode, check.stdout + check.stderr).toBe(0);
  });
});
