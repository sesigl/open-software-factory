import { scenario } from "@opensoftware/testkit";
import { realizingModule, VISION, visionFeature } from "./vision.ts";

scenario("SCN-REPO-127", async ({ sut, given, when, then }) => {
  await given(
    'a vision scenario "SCN-FACTORY-DEMO-001" with the status "planned" and a vision scenario "SCN-FACTORY-DEMO-002" with the status "planned"',
    async () => {
      await sut.files.put(`$INPUT/${VISION}`, visionFeature("planned", "planned"));
    },
  );

  await given(
    'the implemented module scenario "SCN-DEMO-001" and the planned module scenario "SCN-DEMO-002" realize "SCN-FACTORY-DEMO-001"',
    async () => {
      const files = realizingModule("implemented", "planned", "SCN-FACTORY-DEMO-001");
      for (const [path, content] of Object.entries(files)) await sut.files.put(`$INPUT/${path}`, content);
    },
  );

  await given(
    '"docs/vision/README.md" has the marker "generated by make docs from software-factory.feature"',
    async () => {
      await sut.files.put(
        "$INPUT/docs/vision/README.md",
        "# Vision\n\n## Status\n\n<!-- generated by make docs from software-factory.feature: do not edit -->\n\n## Notes\n\nNone.\n",
      );
    },
  );

  let run: Awaited<ReturnType<typeof sut.cli>>;
  await when('the developer runs "osf docs"', async () => {
    run = await sut.cli(["docs"]);
  });

  await then("the command exits with code 0", async () => {
    expect(run.exitCode, run.stdout + run.stderr).toBe(0);
  });

  await then(
    '"docs/vision/README.md" has the row "| SCN-FACTORY-DEMO-001 | planned | SCN-DEMO-001 (implemented), SCN-DEMO-002 (planned) |"',
    async () => {
      const readme = await sut.files.read("$INPUT/docs/vision/README.md");
      expect(readme).toContain(
        "| SCN-FACTORY-DEMO-001 | planned | SCN-DEMO-001 (implemented), SCN-DEMO-002 (planned) |",
      );
    },
  );

  await then('"docs/vision/README.md" has the row "| SCN-FACTORY-DEMO-002 | planned | none |"', async () => {
    const readme = await sut.files.read("$INPUT/docs/vision/README.md");
    expect(readme).toContain("| SCN-FACTORY-DEMO-002 | planned | none |");
  });
});
