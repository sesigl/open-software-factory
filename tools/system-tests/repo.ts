export function prefixes(...rows: [prefix: string, path: string][]): string {
  const lines = rows.map(([prefix, path]) => `| ${prefix} | ${prefix.toLowerCase()} | \`${path}\` |`);
  return ["| Prefix | Owner | Path |", "| --- | --- | --- |", ...lines, ""].join("\n");
}

export const DEMO_PREFIXES = prefixes(["DEMO", "modules/demo/features/"]);

/** A feature file whose first scenario starts on line 5. */
export function feature(...scenarios: string[]): string {
  return ["@module=demo", "Feature: Demo", "", ...scenarios].join("\n");
}

export function scenarioText(id: string, status: string, then = "the command exits with code 0"): string {
  return [
    `  @id=${id} @status=${status}`,
    `  Scenario: ${id}`,
    "    Given an empty folder",
    '    When the user runs "demo run"',
    `    Then ${then}`,
    "",
  ].join("\n");
}

export interface TestOptions {
  extraImport?: string;
  whenLabel?: string;
  cliOptions?: string;
  assertion?: string;
  trailer?: string;
}

/** The system test of SCN-DEMO-001. The when call is on line 7. */
export function systemTest(options: TestOptions = {}): string {
  const {
    extraImport = "",
    whenLabel = 'the user runs "demo run"',
    cliOptions = "",
    assertion = "expect(run.exitCode).toBe(0);",
    trailer = "",
  } = options;
  return [
    'import { scenario } from "@opensoftware/testkit";',
    extraImport,
    "",
    'scenario("SCN-DEMO-001", async ({ sut, given, when, then }) => {',
    '  await given("an empty folder", async () => {});',
    "  let run: Awaited<ReturnType<typeof sut.cli>>;",
    `  await when(${JSON.stringify(whenLabel)}, async () => {`,
    `    run = await sut.cli(["run"]${cliOptions});`,
    "  });",
    '  await then("the command exits with code 0", async () => {',
    `    ${assertion}`,
    "  });",
    "});",
    trailer,
    "",
  ].join("\n");
}

