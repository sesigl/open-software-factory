export function junit(cases: { file: string; id: string; time?: number; body?: string }[]): string {
  const suites = cases.map(({ file, id, time = 0.1, body = "" }) =>
    [
      `  <testsuite name="${file}" tests="1" time="${time}">`,
      `    <testcase classname="${file}" name="${id}" time="${time}">${body}</testcase>`,
      "  </testsuite>",
    ].join("\n"),
  );
  return ['<?xml version="1.0" encoding="UTF-8"?>', "<testsuites>", ...suites, "</testsuites>", ""].join("\n");
}

