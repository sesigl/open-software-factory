import { scenario } from "@opensoftware/testkit";
import { DEMO_PACKAGE, DEMO_PREFIXES } from "./repo.ts";

const SCHEMA = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  type: "object",
  properties: {
    OSF_NOW: { type: "string", description: "The current time.", "x-test-hook": true },
    DEMO_URL: { type: "string", description: "The demo's address." },
  },
};

scenario("SCN-REPO-215", async ({ sut, given, when, then }) => {
  await given(
    'a module whose "src/config.schema.json" has the setting "DEMO_URL" and the test hook "OSF_NOW", marked with "x-test-hook"',
    async () => {
      await sut.files.put("$INPUT/docs/reference/scenario-prefixes.md", DEMO_PREFIXES);
      await sut.files.put("$INPUT/modules/demo/package.json", DEMO_PACKAGE);
      await sut.files.put("$INPUT/modules/demo/src/config.schema.json", `${JSON.stringify(SCHEMA, null, 2)}\n`);
    },
  );

  await given(
    'its README has the marker "generated by make docs from src/config.schema.json" under "## Configuration"',
    async () => {
      await sut.files.put(
        "$INPUT/modules/demo/README.md",
        "# demo\n\n## Configuration\n\n<!-- generated by make docs from src/config.schema.json: do not edit -->\n\n## Notes\n\nNone.\n",
      );
    },
  );

  let run: Awaited<ReturnType<typeof sut.cli>>;
  await when('the developer runs "osf docs"', async () => {
    run = await sut.cli(["docs"]);
  });

  await then("the command exits with code 0", async () => {
    expect(run.exitCode, run.stdout + run.stderr).toBe(0);
  });

  let readme = "";
  await then(
    'the module README has the row "| `DEMO_URL` | string |  | The demo\'s address. |" before the heading "### Test hooks"',
    async () => {
      readme = await sut.files.read("$INPUT/modules/demo/README.md");
      const [settings = "", hooks = ""] = readme.split("\n### Test hooks\n");
      expect(settings).toContain("\n| `DEMO_URL` | string |  | The demo's address. |\n");
      expect(hooks).not.toContain("DEMO_URL");
      expect(settings).not.toContain("OSF_NOW");
    },
  );

  await then(
    'below "### Test hooks" it has the sentence "Only the system tests set these.", then the rows "| `OSF_TEST_HOOKS` | `1` turns the test hooks on. |" and "| `OSF_NOW` | The current time. |"',
    async () => {
      const hooks = readme.split("\n### Test hooks\n")[1]?.split("\n## Notes")[0] ?? "";
      const sentence = hooks.indexOf("Only the system tests set these.");
      const toggle = hooks.indexOf("\n| `OSF_TEST_HOOKS` | `1` turns the test hooks on. |\n");
      const clock = hooks.indexOf("\n| `OSF_NOW` | The current time. |\n");
      expect(sentence).toBeGreaterThan(-1);
      expect(toggle).toBeGreaterThan(sentence);
      expect(clock).toBeGreaterThan(toggle);
    },
  );
});
