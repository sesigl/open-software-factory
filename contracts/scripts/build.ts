// `pnpm build` of @osf/contracts (ADR 0012). TypeSpec in typespec/ is the only hand-written source of the formats.
//
//   1. TypeSpec → one JSON Schema bundle (temporary).
//   2. One self-contained schema per format, references inlined: <format>/<format>.schema.json, committed.
//   3. openapi/openapi.json: OpenAPI 3.1 with the named models, the input of openapi-typescript and oasdiff,
//      committed. JSON, because YAML 1.1 readers turn the key `on` into `true`.
//   4. src/generated/types.ts from openapi.json with openapi-typescript, committed.
//   5. events/asyncapi.yaml must parse with the AsyncAPI parser.
//   6. dist/ with tsc.
//
// `--check` runs 1 to 5 and fails when a committed file differs from what the sources produce.
import { spawnSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { fromFile, Parser } from "@asyncapi/parser";
import openapiTS, { astToString } from "openapi-typescript";
import { FORMATS } from "../src/formats.ts";

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
type JsonObject = { [key: string]: Json };

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const REPO = join(ROOT, "..");
const SCHEMA_BASE = "https://raw.githubusercontent.com/sesigl/open-software-factory/main/contracts";
const GENERATED_NOTE = "Generated by `pnpm build` in contracts/ from typespec/. Do not edit.";

const check = process.argv.includes("--check");
const files = new Map<string, string>();

const bundle = compileTypeSpec();
for (const format of FORMATS) {
  const root = bundle[format.model] as JsonObject | undefined;
  if (!root) throw new Error(`typespec/ has no model ${format.model} for the format ${format.name}`);
  const schema: JsonObject = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: `${SCHEMA_BASE}/${format.path}/${format.name}.schema.json`,
    title: format.model,
    $comment: GENERATED_NOTE,
    ...(inline(root, bundle, (root.$defs as JsonObject) ?? {}) as JsonObject),
  };
  files.set(`${format.path}/${format.name}.schema.json`, `${JSON.stringify(schema, null, 2)}\n`);
}
const openapi = openApi(bundle);
files.set("openapi/openapi.json", `${JSON.stringify(openapi, null, 2)}\n`);
files.set("src/generated/types.ts", await types(openapi));
await checkAsyncApi();

if (check) {
  const stale = [...files].filter(
    ([path, text]) => !existsSync(join(ROOT, path)) || readFileSync(join(ROOT, path), "utf8") !== text,
  );
  for (const [path] of stale) process.stderr.write(`contracts/${path} is out of date: run pnpm build in contracts/\n`);
  process.exit(stale.length === 0 ? 0 : 1);
}

for (const [path, text] of files) {
  mkdirSync(dirname(join(ROOT, path)), { recursive: true });
  writeFileSync(join(ROOT, path), text);
}
rmSync(join(ROOT, "dist"), { recursive: true, force: true });
run("tsc", ["-p", "tsconfig.build.json"], ROOT, binOf("typescript", "tsc"));

/** TypeSpec → the `$defs` of one bundle, keyed by model name. */
function compileTypeSpec(): JsonObject {
  const out = mkdtempSync(join(tmpdir(), "osf-contracts-"));
  try {
    run(
      process.execPath,
      [
        binOf("@typespec/compiler", "tsp"),
        "compile",
        "typespec/main.tsp",
        "--emit",
        "@typespec/json-schema",
        "--option",
        "@typespec/json-schema.file-type=json",
        "--option",
        "@typespec/json-schema.bundleId=bundle.json",
        "--option",
        `@typespec/json-schema.emitter-output-dir=${out}`,
        "--warn-as-error",
      ],
      ROOT,
    );
    return (JSON.parse(readFileSync(join(out, "bundle.json"), "utf8")) as JsonObject).$defs as JsonObject;
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}

/** Replaces every `$ref` by its target, so one file holds the whole format. TypeSpec models are never recursive. */
function inline(node: Json, defs: JsonObject, local: JsonObject, isMap = false): Json {
  if (Array.isArray(node)) return node.map((item) => inline(item, defs, local));
  if (node === null || typeof node !== "object") return node;
  const scope = { ...local, ...((node.$defs as JsonObject | undefined) ?? {}) };
  if (!isMap && typeof node.$ref === "string") {
    const { $ref, ...rest } = node;
    const target = resolve($ref, defs, scope);
    const targetScope = { ...scope, ...((target.$defs as JsonObject | undefined) ?? {}) };
    return { ...(inline(target, defs, targetScope) as JsonObject), ...(inline(rest, defs, scope) as JsonObject) };
  }
  const out: JsonObject = {};
  for (const [key, value] of Object.entries(node)) {
    if (!isMap && (key === "$schema" || key === "$id" || key === "$defs")) continue;
    out[key] = inline(value, defs, scope, !isMap && key === "properties");
  }
  return out;
}

function resolve(ref: string, defs: JsonObject, local: JsonObject): JsonObject {
  const target = ref.startsWith("#/$defs/") ? local[ref.slice("#/$defs/".length)] : defs[ref.replace(/\.json$/, "")];
  if (!target || typeof target !== "object" || Array.isArray(target)) throw new Error(`Unresolved $ref ${ref}`);
  return target;
}

/** OpenAPI 3.1 whose components are the named models, so generated classes get the TypeSpec names. */
function openApi(defs: JsonObject): JsonObject {
  const manifest = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")) as { version: string };
  const toComponents = (node: Json, local: JsonObject, isMap = false): Json => {
    if (Array.isArray(node)) return node.map((item) => toComponents(item, local));
    if (node === null || typeof node !== "object") return node;
    const scope = { ...local, ...((node.$defs as JsonObject | undefined) ?? {}) };
    if (!isMap && typeof node.$ref === "string") {
      const { $ref, ...rest } = node;
      const own = toComponents(rest, scope) as JsonObject;
      if ($ref.startsWith("#/$defs/"))
        return { ...(toComponents(resolve($ref, defs, scope), scope) as JsonObject), ...own };
      return { $ref: `#/components/schemas/${$ref.replace(/\.json$/, "")}`, ...own };
    }
    const out: JsonObject = {};
    for (const [key, value] of Object.entries(node)) {
      if (!isMap && (key === "$schema" || key === "$id" || key === "$defs")) continue;
      out[key] = toComponents(value, scope, !isMap && key === "properties");
    }
    return out;
  };
  const schemas: JsonObject = {};
  for (const name of Object.keys(defs).sort()) schemas[name] = toComponents(defs[name] as Json, {});
  return {
    openapi: "3.1.0",
    info: {
      title: "Open Software Factory contracts",
      version: manifest.version,
      description: `The shared formats as named models. No operations: module APIs are added per module. ${GENERATED_NOTE}`,
      license: { name: "Apache-2.0", identifier: "Apache-2.0" },
    },
    paths: {},
    components: { schemas },
  };
}

async function types(openapi: JsonObject): Promise<string> {
  const ast = await openapiTS(openapi as unknown as Parameters<typeof openapiTS>[0], { exportType: true });
  return `// ${GENERATED_NOTE}\n${astToString(ast)}`;
}

async function checkAsyncApi(): Promise<void> {
  // The payloads reference the event schemas, so the parser reads the files written above.
  const temp = mkdtempSync(join(tmpdir(), "osf-asyncapi-"));
  try {
    cpSync(join(ROOT, "events", "asyncapi.yaml"), join(temp, "events", "asyncapi.yaml"));
    for (const [path, text] of files) {
      if (!path.startsWith("events/")) continue;
      mkdirSync(dirname(join(temp, path)), { recursive: true });
      writeFileSync(join(temp, path), text);
    }
    const { document, diagnostics } = await fromFile(new Parser(), join(temp, "events", "asyncapi.yaml")).parse();
    const problems = diagnostics.filter((diagnostic) => diagnostic.severity <= 1);
    for (const problem of problems) {
      process.stderr.write(`contracts/events/asyncapi.yaml ${problem.path.join(".")}: ${problem.message}\n`);
    }
    if (!document || problems.length > 0) throw new Error("contracts/events/asyncapi.yaml is not valid AsyncAPI");
  } finally {
    rmSync(temp, { recursive: true, force: true });
  }
}

function binOf(pkg: string, bin: string): string {
  const candidates = [ROOT, REPO].map((dir) => join(dir, "node_modules", pkg, "package.json"));
  const manifest = candidates.find((file) => existsSync(file)) ?? (candidates[0] as string);
  const { bin: bins } = JSON.parse(readFileSync(manifest, "utf8")) as { bin: Record<string, string> };
  return join(dirname(manifest), bins[bin] as string);
}

function run(command: string, args: string[], cwd: string, script?: string): void {
  const [file, argv] = script ? [process.execPath, [script, ...args]] : [command, args];
  // Output only on failure: a build that works is quiet.
  const result = spawnSync(file, argv, { cwd, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  if (result.status !== 0) {
    process.stderr.write(`${result.stdout ?? ""}${result.stderr ?? ""}`);
    throw new Error(`${command} ${args.join(" ")} failed with exit code ${result.status}`);
  }
}
